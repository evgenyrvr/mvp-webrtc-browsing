#!/bin/sh
set -eu
project_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$project_root"
python3 testing/publication-check.py
./tools/go.sh test ./...
./tools/go.sh vet ./...
./tools/go.sh build ./...
if command -v gcc >/dev/null 2>&1 || command -v clang >/dev/null 2>&1; then
  CGO_ENABLED=1 ./tools/go.sh test -race ./...
else
  printf '%s\n' 'Race detector not run: install a C compiler and run CGO_ENABLED=1 ./tools/go.sh test -race ./...'
fi
